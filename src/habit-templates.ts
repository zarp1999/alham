export function filterTemplates(query: string, category: string) {
 const terms=query.normalize('NFKC').toLowerCase().trim().split(/\s+/).filter(Boolean);
 return habitTemplates.filter(t => (!category || t.category===category) && terms.every(term => (t.name+' '+t.action+' '+t.category+' '+tr(t.name)+' '+tr(t.action)+' '+tr(t.category)).normalize('NFKC').toLowerCase().includes(term)));
}
